#!/usr/bin/env python3
"""Cross-build the Rust ROS2 controller and stage an ament-discoverable package.

Target libraries/IDL are copied from the car to the engineering work directory;
Rust interfaces are generated by ros2-generate-rust.py. No vehicle operation.
"""
import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import tarfile

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--ros-prefix', type=Path, required=True)
parser.add_argument('--interfaces', type=Path, required=True)
parser.add_argument('--out', type=Path, required=True)
parser.add_argument('--require-clean', action='store_true')
parser.add_argument('--binary', type=Path, help='stage an already cross-built ROS2 executable after ELF validation')
args = parser.parse_args()
prefix, interfaces, out = args.ros_prefix.resolve(), args.interfaces.resolve(), args.out.resolve()
if args.require_clean:
    subprocess.run(['git', 'diff', '--exit-code', 'HEAD', '--'], cwd=ROOT, check=True)
out.mkdir(parents=True, exist_ok=True)
target = out/'target'
env = dict(os.environ, RUSTUP_TOOLCHAIN='1.97.1', ROS_DISTRO='humble',
    AMENT_PREFIX_PATH=os.pathsep.join(map(str, [interfaces, prefix])), CARGO_TARGET_DIR=str(target),
    CARGO_ZIGBUILD_ZIG_PATH=str(ROOT/'toolchains/zig-aarch64-macos-0.15.2/zig'),
    CARGO_ZIGBUILD_CACHE_DIR=str(ROOT/'tmp/cargo-zigbuild-cache'), ZIG_GLOBAL_CACHE_DIR=str(ROOT/'tmp/zig-cache'),
    RUSTFLAGS='-C link-arg=-Wl,-rpath,/opt/ros/humble/lib -C link-arg=-Wl,--disable-new-dtags -C link-arg=-Wl,--allow-shlib-undefined')
if args.binary is None:
    subprocess.run([str(ROOT/'toolchains/cargo-zigbuild-0.23.4/cargo-zigbuild'), 'zigbuild',
        '--manifest-path', str(ROOT/'route-engine/Cargo.toml'), '--features', 'ros2', '--release', '--locked', '--offline',
        '--target', 'riscv64gc-unknown-linux-gnu.2.38'], env=env, check=True, cwd=ROOT)
binary = args.binary.resolve() if args.binary else target/'riscv64gc-unknown-linux-gnu/release/route-engine'
subprocess.run(['python3', '-B', str(ROOT/'scripts/inspect_elf.py'), str(binary),
    '--profile', 'ros2-humble', '--output', str(out/'elf.json')], check=True, cwd=ROOT)
install = out/'install'
package = install/'share/xt_stcar_race'
executable = install/'lib/xt_stcar_race/route-engine'
resource = install/'share/ament_index/resource_index/packages/xt_stcar_race'
for path in [package, executable.parent, resource.parent]:
    path.mkdir(parents=True, exist_ok=True)
shutil.copy2(binary, executable)
executable.chmod(0o755)
shutil.copy2(ROOT/'ros2/xt_stcar_race/package.xml', package/'package.xml')
shutil.copytree(ROOT/'ros2/xt_stcar_race/launch', package/'launch', dirs_exist_ok=True)
resource.write_text('')
(install/'setup.bash').write_text('''# Source this file; keep the target vendor ROS installation unchanged.
source /opt/ros/humble/setup.bash || return
_stcar_prefix="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
export AMENT_PREFIX_PATH="${_stcar_prefix}${AMENT_PREFIX_PATH:+:$AMENT_PREFIX_PATH}"
export ROS_DOMAIN_ID=217 RMW_IMPLEMENTATION=rmw_fastrtps_cpp
unset _stcar_prefix
''')
source = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
dirty = subprocess.run(['git', 'diff', '--quiet', 'HEAD', '--'], cwd=ROOT).returncode != 0
manifest = {'source_commit': source, 'source_dirty': dirty, 'ros_distro': 'humble', 'rclrs': '0.8.0',
    'rmw': 'rmw_fastrtps_cpp', 'target': 'riscv64gc-unknown-linux-gnu.2.38', 'features': ['ros2'],
    'physical_trial_executed': False, 'nodes': ['xt_stcar_race', 'xt_stcar_chassis', 'xt_stcar_lidar'],
    'hardware_transport': 'ROS2 topics; separate driver processes retain native Guard and EOF lifeline',
    'binary': str(executable.relative_to(out)), 'ros_prefix_for_link': str(prefix), 'rust_interface_overlay': str(interfaces)}
if not dirty:
    source_archive = package/'competition-source.tar.gz'
    subprocess.run(['git', 'archive', '--format=tar.gz', '--output', str(source_archive), 'HEAD',
        'Cargo.toml', 'Cargo.lock', 'rust-toolchain.toml', 'route-engine', 'crates', 'config',
        'scripts/race-trial.py', 'scripts/vision-log.py', 'scripts/build-ros2-race.py',
        'scripts/ros2-generate-rust.py', 'scripts/package-ros2-round.py', 'scripts/inspect_elf.py', 'ros2/xt_stcar_race'],
        cwd=ROOT, check=True)
    manifest['source_archive'] = str(source_archive.relative_to(install))
(out/'manifest.json').write_text(json.dumps(manifest, indent=2)+'\n')
with tarfile.open(out/'xt-stcar-ros2-install.tar.gz', 'w:gz') as archive:
    archive.add(install, arcname='install')
    archive.add(out/'manifest.json', arcname='manifest.json')
print(json.dumps(manifest, indent=2))
